const { app, BrowserWindow } = require('electron')
app.commandLine.appendSwitch('force-device-scale-factor', '1')
const path = require('path'), fs = require('fs')
app.whenReady().then(async () => {
  const w = new BrowserWindow({ width: 1024, height: 1024, show: false, transparent: true, frame: false, useContentSize: true, webPreferences: { offscreen: true, zoomFactor: 1 } })
  await w.loadFile(path.join(__dirname, '..', 'resources', 'icon.html'))
  await new Promise(r => setTimeout(r, 500))
  const img = await w.webContents.capturePage({ x: 0, y: 0, width: 1024, height: 1024 })
  const png = img.resize({ width: 1024, height: 1024 }).toPNG()
  fs.writeFileSync(path.join(__dirname, '..', 'resources', 'icon.png'), png)
  fs.mkdirSync(path.join(__dirname, '..', 'build'), { recursive: true })
  fs.writeFileSync(path.join(__dirname, '..', 'build', 'icon.png'), png)
  console.log('icon written', png.length)
  app.quit()
})
